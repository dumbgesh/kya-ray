def test_scenario_d_promotion_failure_triggers_automatic_rollback(isolated_env):
    """
    Simulates a Windows sharing violation during promotion after backup was created.
    Proves automatic rollback restores Version A and preserves user .env.
    """
    install_dir = isolated_env["install_dir"]
    data_dir = isolated_env["data_dir"]
    v2_zip = isolated_env["package_meta"]["v2_zip"]
    reg_mgr = isolated_env["reg_mgr"]

    installer = UpdateInstaller(
        install_dir=install_dir,
        data_dir=data_dir,
        registry_manager=reg_mgr,
    )

    # Inject failure during atomic move in promotion phase ONLY (fail_count == 0)
    original_atomic_move = installer._atomic_move
    fail_count = 0

    def failing_move(src, dst):
        nonlocal fail_count
        if str(dst) == str(install_dir) and fail_count == 0:
            fail_count += 1
            raise OSError(32, "The process cannot access the file because it is being used by another process")
        return original_atomic_move(src, dst)

    installer._atomic_move = failing_move

    result = installer.install(
        zip_path=v2_zip,
        target_version="1.0.0-beta.2",
        restart_after=False,
    )

    assert result.success is False
    assert result.rollback_status == RollbackStatus.SUCCEEDED
    assert "used by another process" in result.error_message

    # Verify Version A was restored by rollback
    assert (install_dir / "v1_marker.txt").is_file()
    assert not (install_dir / "v2_marker.txt").exists()
    assert (install_dir / "Kya-Ray.exe").is_file()
    assert "USER_CUSTOM_SETTING=preserved_value_alpha" in (install_dir / ".env").read_text()
    assert reg_mgr.get_display_version() == "1.0.0-beta.1"


def test_scenario_e_startup_handshake_timeout_with_real_pe_binary(isolated_env, tmp_path):
    """
    Scenario E: Creates a genuine Windows PE executable that sleeps without writing handshake.
    Validates that real timeout terminates the process and automatically rolls back to Version A.
    """
    install_dir = isolated_env["install_dir"]
    data_dir = isolated_env["data_dir"]
    reg_mgr = isolated_env["reg_mgr"]

    # 1. Compile genuine Windows PE executable using PowerShell Add-Type
    silent_exe_path = tmp_path / "Kya-Ray.exe"
    csharp_code = "public class Program { public static void Main(string[] args) { System.Threading.Thread.Sleep(30000); } }"
    compile_cmd = [
        "powershell", "-NoProfile", "-Command",
        f'Add-Type -TypeDefinition "{csharp_code}" -OutputAssembly "{silent_exe_path}" -OutputType WindowsApplication'
    ]
    compile_res = subprocess.run(compile_cmd, capture_output=True, text=True)
    assert compile_res.returncode == 0
    assert silent_exe_path.is_file()
    with open(silent_exe_path, "rb") as f:
        assert f.read(2) == b"MZ", "Compiled binary must have Windows PE MZ header"

    # 2. Package into valid release ZIP with _internal dependencies
    silent_zip_path = tmp_path / "silent_hanging_release.zip"
    with zipfile.ZipFile(silent_zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(silent_exe_path, arcname="Kya-Ray/Kya-Ray.exe")
        # Add runtime dependencies
        v1_dist = Path(isolated_env["package_meta"]["v1_dist"])
        for item in (v1_dist / "_internal").rglob("*"):
            if item.is_file():
                rel = item.relative_to(v1_dist)
                zf.write(item, arcname=f"Kya-Ray/{rel}")

    # 3. Execute installation with bounded handshake timeout
    installer = UpdateInstaller(
        install_dir=install_dir,
        data_dir=data_dir,
        registry_manager=reg_mgr,
        handshake_timeout=2.0,  # 2.0s bounded timeout
    )

    result = installer.install(
        zip_path=silent_zip_path,
        target_version="1.0.0-beta.2",
        restart_after=True,
    )

    assert result.success is False
    assert result.rollback_status == RollbackStatus.SUCCEEDED
    assert "readiness handshake" in result.error_message or "timed out" in result.error_message

    # Verify Version A was cleanly restored
    assert (install_dir / "v1_marker.txt").is_file()
    assert (install_dir / "Kya-Ray.exe").is_file()
    assert reg_mgr.get_display_version() == "1.0.0-beta.1"


