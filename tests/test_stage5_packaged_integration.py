def test_complete_packaged_update_happy_path(isolated_env):
    """Executes a real update using the packaged standalone updater binary in detached mode."""
    install_dir = isolated_env["install_dir"]
    data_dir = isolated_env["data_dir"]
    run_dir = isolated_env["run_dir"]
    v2_zip = isolated_env["package_meta"]["v2_zip"]
    reg_mgr = isolated_env["reg_mgr"]

    kya_exe = install_dir / "Kya-Ray.exe"
    assert kya_exe.is_file()

    # Preflight assertions
    assert (install_dir / "v1_marker.txt").is_file()
    assert not (install_dir / "v2_marker.txt").exists()
    assert reg_mgr.get_display_version() == "1.0.0-beta.1"

    # Prepare detached updater copy outside install_dir (identical to launch_detached_updater)
    # This guarantees zero locked files inside install_dir on Windows
    detached_dir = run_dir / "detached_updater"
    detached_dir.mkdir(parents=True, exist_ok=True)
    detached_exe = detached_dir / "Kya-Ray.exe"
    shutil.copy2(kya_exe, detached_exe)
