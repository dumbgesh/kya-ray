    assert "gsk_test_dummy_isolated_mock_key_98765" in env_content
    assert "USER_CUSTOM_SETTING=preserved_value_alpha" in env_content

    # Verify Registry Update
    assert reg_mgr.get_display_version() == "1.0.0-beta.2"

    # Verify Staging & Backup Cleanup
    parent_dir = install_dir.parent
    stray_backups = list(parent_dir.glob("Kya-Ray.backup-*"))
    stray_stagings = list(parent_dir.glob(".kya-ray-staging-*"))
    assert len(stray_backups) == 0, f"Stray backups left: {stray_backups}"
    assert len(stray_stagings) == 0, f"Stray stagings left: {stray_stagings}"


