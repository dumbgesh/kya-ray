def find_latest_manifest() -> dict:
    """Finds the manifest generated by prepare_packages.py."""
    test_env_dir = Path(r"C:\kya-ray\test_env")
    manifests = list(test_env_dir.glob("stage5_*/manifest.json"))
    if not manifests:
        pytest.skip("Build manifest not found. Run prepare_packages.py first.")
    manifests.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    with open(manifests[0], "r", encoding="utf-8") as f:
        return json.load(f)


